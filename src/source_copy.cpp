std::filesystem::path validate_source_copy_destination(const std::filesystem::path& project,
                                                       const std::filesystem::path& folder) {
    return destination(ProjectPaths(project), folder);
}
SourceCopyPlan prepare_generated_source_copy(const std::filesystem::path& project,
                                             const std::filesystem::path& new_folder,
                                             const std::filesystem::path& name,
                                             std::vector<std::byte> bytes,
                                             std::string catalog_digest, std::stop_token stop) {
    return prepare_shared_generated_source_copy(
        project, new_folder, name, std::make_shared<const std::vector<std::byte>>(std::move(bytes)),
        std::move(catalog_digest), stop);
}
SourceCopyPlan prepare_shared_generated_source_copy(
    const std::filesystem::path& project, const std::filesystem::path& new_folder,
    const std::filesystem::path& name, std::shared_ptr<const std::vector<std::byte>> bytes,
    std::string catalog_digest, std::stop_token stop) {
    cancel(stop);
    const ProjectPaths paths(project);
    (void)destination(paths, new_folder);
    require(!name.empty() && name == name.filename(), "Generated source needs a plain filename");
    raw_path(name);
    require(bytes && !bytes->empty() && bytes->size() <= file_limit,
            "Generated source must contain at most512MiB of raw bytes");
    require(catalog_digest.empty() || catalog_digest.size() == 64,
            "Generated source input catalog revision is invalid");
    SourceCopyPlan result{paths.root(), new_folder, {}, {name}, bytes->size()};
    result.catalog_digest = std::move(catalog_digest);
    const auto digest = asset_detail::content_digest(*bytes);
    result.files.push_back({{}, name, digest, bytes->size(), std::move(bytes)});
    return result;
}
SourceCopyPlan
prepare_generated_source_revision(const std::filesystem::path& project, AssetId asset,
                                  std::shared_ptr<const std::vector<std::byte>> bytes,
                                  std::string catalog_digest, std::stop_token stop) {
    const ProjectPaths paths(project);
    auto [source, revision] = source_revision(paths, asset, catalog_digest, stop);
    require(bytes && !bytes->empty() && bytes->size() <= file_limit,
            "Generated source must contain at most512MiB of raw bytes");
    SourceCopyPlan result{
        paths.root(), source.parent_path(), {}, {source.filename()}, bytes->size()};
    result.catalog_digest = std::move(catalog_digest);
    result.revision = std::move(revision);
    const auto digest = asset_detail::content_digest(*bytes);
    result.files.push_back({{}, source.filename(), digest, bytes->size(), std::move(bytes)});
    return result;
}
SourceCopyPlan prepare_source_copy(const std::filesystem::path& project,
                                   const std::filesystem::path& new_folder,
                                   const std::vector<std::filesystem::path>& files,
                                   const std::set<std::string>& extensions, std::stop_token stop,
                                   const SourceCopyInspector& fbx_inspector) {
    const ProjectPaths paths(project);
    (void)destination(paths, new_folder);
    require(!files.empty() && files.size() <= 256, "Select between1 and256 source files");
    SourceCopyPlan result{paths.root(), new_folder, {}, {}, 0};
    std::set<std::filesystem::path, ProjectLocatorLess> selected;
    for (const auto& file : files) {
        cancel(stop);
        const auto path = std::filesystem::absolute(file).lexically_normal();
        asset_storage::ordinary(path);
        require(std::filesystem::is_regular_file(path), "Selected source must be an ordinary file");
        require(selected.insert(path).second, "The same source was selected more than once");
        raw_path(path.filename());
        const auto folder =
            std::filesystem::path("Source-" + std::to_string(result.sources.size() + 1));
        result.sources.push_back(folder / path.filename());
        std::map<std::filesystem::path, std::string, ProjectLocatorLess> dependencies;
        const auto extension = lower(path_utf8(path.extension()));
        if (extension == ".gltf" || extension == ".glb") {
            const auto bundle =
                capture_gltf_source(path.parent_path(), path.filename(), extensions, {}, stop);
            dependencies.emplace(path.filename(), bundle.source_digest);
            for (const auto& dependency : bundle.dependencies)
                dependencies.emplace(dependency.source, dependency.revision);
        } else if (extension == ".fbx") {
            require(bool(fbx_inspector),
                    "FBX source copying requires the supervised model inspector");
            for (const auto& dependency : fbx_inspector(path, stop)) {
                const auto [at, added] =
                    dependencies.emplace(dependency.source, dependency.revision);
                require(added || at->second == dependency.revision,
                        "Conflicting FBX source-copy revisions");
            }
            require(dependencies.contains(path.filename()),
                    "FBX inspector omitted its source revision");
        } else {
            const auto bytes = asset_detail::read_bytes(path, file_limit);
            dependencies.emplace(path.filename(), asset_detail::content_digest(bytes));
        }
        for (const auto& [relative, expected] : dependencies) {
            cancel(stop);
            raw_path(relative);
            const auto original = ProjectPaths(path.parent_path()).resolve(relative);
            asset_storage::ordinary(original);
            const auto size = std::filesystem::file_size(original);
            require(size <= file_limit && size <= batch_limit - result.bytes &&
                        result.files.size() < 8192,
                    "Source copy exceeds512MiB per file,2GiB total or8192 files");
            result.bytes += size;
            result.files.push_back({original, folder / relative, expected, size});
        }
    }
    return result;
}
SourceCopyCommit commit_source_copy(const ProjectLease& lease, const SourceCopyPlan& plan,
                                    std::stop_token stop) {
    lease.check();
    const ProjectPaths paths(lease.root());
    require(paths.root() == plan.project, "Source-copy plan belongs to another project");
    require(!plan.files.empty() && plan.files.size() <= 8192 && plan.bytes <= batch_limit,
            "Invalid source-copy plan bounds");
    check_catalog(paths, plan.catalog_digest);
    cancel(stop);
    if (plan.revision) {
        require(plan.files.size() == 1 && plan.sources.size() == 1,
                "Generated source revision must replace exactly one file");
        const auto& file = plan.files.front();
        require(file.generated && file.original.empty() && file.bytes > 0 &&
                    file.bytes <= file_limit && file.bytes == plan.bytes &&
                    file.generated->size() == file.bytes &&
                    asset_detail::content_digest(*file.generated) == file.digest,
                "Generated source revision bytes changed after review");
        const auto check_revision = [&] {
            const auto [source, revision] =
                source_revision(paths, plan.revision->asset, plan.catalog_digest, stop);
            require(source == plan.destination / file.destination &&
                        file.destination == source.filename() &&
                        plan.sources.front() == file.destination &&
                        revision.source_digest == plan.revision->source_digest &&
                        revision.sidecar_digest == plan.revision->sidecar_digest,
                    "Generated source revision changed after review");
            return paths.resolve(source);
        };
        (void)check_revision();
#ifdef FORGE_SOURCE_COPY_TESTING
        source_copy_before_rename();
#endif
        lease.check();
        const auto target = check_revision();
        try {
            asset_storage::replace(
                target, std::string_view(reinterpret_cast<const char*>(file.generated->data()),
                                         file.generated->size()));
#ifdef FORGE_SOURCE_COPY_TESTING
            source_copy_after_publish();
#endif
        } catch (const std::exception& error) {
            // Atomic replacement can succeed before a final durability check
            // fails. Never report that committed generated bytes were discarded.
            try {
                if (asset_detail::content_digest(asset_detail::read_bytes(target, file_limit)) ==
                    file.digest)
                    return {std::string("Source revision committed; final write check failed: ") +
                            error.what()};
            } catch (const std::exception&) {
            }
            throw;
        }
        return {};
    }
    const auto target = destination(paths, plan.destination);
    const auto staging = target.parent_path() / (".forge-import-" + AssetId::generate().str());
    require(std::filesystem::create_directory(staging),
            "Cannot create isolated source-copy staging");
    std::map<std::filesystem::path, std::string> written;
    std::set<std::filesystem::path> directories{staging};
    bool published = false;
    try {
        const ProjectPaths staged(staging);
        std::set<std::filesystem::path, ProjectLocatorLess> destinations;
        std::uint64_t total = 0;
        for (const auto& entry : plan.files) {
            cancel(stop);
            lease.check();
            raw_path(entry.destination);
            require(destinations.insert(entry.destination).second && entry.bytes <= file_limit &&
                        entry.bytes <= batch_limit - total,
                    "Duplicate or excessive source-copy destination");
            total += entry.bytes;
            std::vector<std::byte> external;
            std::span<const std::byte> bytes;
            if (entry.generated) {
                require(entry.original.empty(),
                        "Generated source cannot also name an external file");
                bytes = *entry.generated;
            } else {
                asset_storage::ordinary(entry.original);
                external = asset_detail::read_bytes(entry.original, file_limit);
                bytes = external;
            }
            require(bytes.size() == entry.bytes &&
                        asset_detail::content_digest(bytes) == entry.digest,
                    "A source changed after review; prepare the import again");
            const auto path = staged.resolve(entry.destination);
            for (auto parent = path.parent_path(); parent != staging; parent = parent.parent_path())
                directories.insert(parent);
            std::filesystem::create_directories(path.parent_path());
            asset_storage::replace(
                path, std::string_view(reinterpret_cast<const char*>(bytes.data()), bytes.size()));
            written.emplace(path, entry.digest);
        }
        require(total == plan.bytes, "Source-copy plan byte count mismatch");
        cancel(stop);
        for (auto it = directories.rbegin(); it != directories.rend(); ++it)
            asset_storage::sync_directory(*it);
        lease.check();
        (void)destination(paths, plan.destination);
#ifdef FORGE_SOURCE_COPY_TESTING
        source_copy_before_rename();
#endif
        check_catalog(paths, plan.catalog_digest);
        asset_detail::rename_new_directory(staging, target);
        published = true;
#ifdef FORGE_SOURCE_COPY_TESTING
        source_copy_after_publish();
#endif
        asset_storage::sync_directory(target.parent_path());
    } catch (const std::exception& error) {
        if (published)
            return {std::string("Source folder committed; final write check failed: ") +
                    error.what()};
        // Retire only bytes this operation wrote. Unknown/externally changed
        // staging files remain for inspection instead of recursive deletion.
        std::error_code ignored;
        for (const auto& [path, digest] : written) {
            try {
                const auto bytes = asset_detail::read_bytes(path, file_limit);
                if (asset_detail::content_digest(bytes) == digest)
                    std::filesystem::remove(path, ignored);
            } catch (const std::exception&) {
            }
        }
        for (auto it = directories.rbegin(); it != directories.rend(); ++it)
            std::filesystem::remove(*it, ignored);
        throw std::runtime_error(
            std::string(error.what()) +
            (std::filesystem::exists(staging) ? "; preserved staging: " + path_utf8(staging) : ""));
    }
    return {};
}
