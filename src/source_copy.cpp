constexpr std::uint64_t file_limit = 512ull * 1024 * 1024;
constexpr std::uint64_t batch_limit = 2ull * 1024 * 1024 * 1024;
void require(bool condition, const char* message) {
    if (!condition)
        throw std::runtime_error(message);
}
void cancel(std::stop_token stop) {
    require(!stop.stop_requested(), "Source copy cancelled; no destination published");
}
std::string lower(std::string value) {
    for (auto& c : value)
        if (c >= 'A' && c <= 'Z')
            c += 'a' - 'A';
    return value;
}
void raw_path(const std::filesystem::path& relative) {
    (void)ProjectPaths::normalize(relative);
    for (const auto& part : relative) {
        const auto name = lower(path_utf8(part));
        require(
            !name.starts_with('.') && !name.ends_with(".forge-import.json") &&
                name != "forge.project.json" && name != "forge.assets.json" &&
                name != "forge.components.json" && !name.ends_with(".scene.json") &&
                !name.ends_with(".prefab.json") && !name.ends_with(".material.json") &&
                !name.ends_with(".collision.json") && !name.ends_with(".shader.json"),
            "Import raw sources only; project/asset identities and hidden files are not copied");
    }
}
std::filesystem::path destination(const ProjectPaths& paths, const std::filesystem::path& folder) {
    require(ProjectPaths::normalize(folder) == folder && folder.begin()->string() == "Assets" &&
                std::distance(folder.begin(), folder.end()) >= 2,
            "Choose a new folder below Assets");
    raw_path(folder);
    const auto path = paths.resolve(folder);
    asset_storage::ordinary(path);
    require(!std::filesystem::exists(path) && std::filesystem::is_directory(path.parent_path()),
            "Import destination already exists or its parent folder is missing; choose a new name");
    return path;
}
void check_catalog(const ProjectPaths& paths, const std::string& digest) {
    if (digest.empty())
        return;
    require(valid_content_digest(digest), "Generated source input catalog revision is invalid");
    const auto index = AssetCatalog::project_index(paths.root());
    const auto bytes = asset_storage::read(index, max_asset_index_bytes);
    require(!bytes || !bytes->empty(), "Generated source input catalog is empty");
    const auto text = bytes ? std::string_view(*bytes) : std::string_view{};
    require(asset_detail::content_digest(std::as_bytes(std::span(text))) == digest,
            "Generated source inputs changed; prepare the review again");
}
std::pair<std::filesystem::path, GeneratedSourceRevision>
source_revision(const ProjectPaths& paths, AssetId asset, const std::string& catalog_digest,
                std::stop_token stop) {
    cancel(stop);
    require(bool(asset) && !catalog_digest.empty(),
            "Generated source revision requires a registered asset and input catalog");
    check_catalog(paths, catalog_digest);
    const auto catalog = AssetCatalog::open_project(paths.root());
    const auto at = catalog.records().find(asset);
    require(at != catalog.records().end() && !at->second.subasset,
            "Generated source revision requires an independent registered asset");
    const auto& record = at->second;
    const auto& source = record.source;
    raw_path(source);
    require(source.begin()->string() == "Assets" &&
                std::distance(source.begin(), source.end()) >= 2,
            "Generated source revision must stay below Assets");
    for (const auto& [id, other] : catalog.records())
        require(id == asset || !paths.same_locator(other.source, source),
                "Generated source revision cannot replace a shared model or source family");
    const auto imported = record.metadata.find("forge.import");
    require(imported != record.metadata.end() && imported->is_object(),
            "Reimport this source before updating its generated bytes");
    GeneratedSourceRevision revision{asset, imported->at("source_digest").get<std::string>(),
                                     imported->at("sidecar_digest").get<std::string>()};
    require(valid_content_digest(revision.source_digest) &&
                valid_content_digest(revision.sidecar_digest),
            "Generated source import revisions are invalid");
    const auto bytes = asset_detail::read_bytes(paths.resolve(source), file_limit);
    const auto sidecar = asset_storage::read(paths.resolve(AssetPublisher::sidecar_path(source)),
                                             max_asset_index_bytes);
    require(sidecar && !sidecar->empty() &&
                asset_detail::content_digest(bytes) == revision.source_digest &&
                asset_detail::content_digest(std::as_bytes(std::span(*sidecar))) ==
                    revision.sidecar_digest,
            "Generated source or settings changed; reimport before rebaking");
    const auto identity = AssetImportSidecar::parse(*sidecar);
    require(identity.identity.owner == asset &&
                paths.same_locator(identity.identity.source, source) &&
                identity.identity.source_digest == revision.source_digest &&
                identity.identity.entries.empty() &&
                nlohmann::json(identity.settings.importer) == imported->at("importer"),
            "Generated source identity/settings disagree with the catalog");
    cancel(stop);
    return {source, std::move(revision)};
}
